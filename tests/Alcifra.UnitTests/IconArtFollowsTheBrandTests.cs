using System.Text.RegularExpressions;

namespace Alcifra.UnitTests;

/// <summary>
/// The launcher icon takes its colours from the design tokens, and keeps doing so (ADR 0578).
/// </summary>
/// <remarks>
/// <para>
/// The icon is the half of a rebrand nobody remembers. An application whose window is one colour and whose Dock
/// tile is another looks unfinished in a way users notice before they can name it — and the failure is silent,
/// because the icon still renders perfectly, just in last year's colour.
/// </para>
/// <para>
/// <b>Deliberately not a byte comparison of the generated PNGs.</b> They come out of Skia, whose output moves
/// with its version, so a guard on the bytes would fail on an unrelated dependency bump — and a flaky guard is
/// worse than none, because the first thing anyone does with one is stop reading it. What is asserted instead
/// is the property that actually matters: the art names no colour of its own.
/// </para>
/// </remarks>
public partial class IconArtFollowsTheBrandTests
{
    [GeneratedRegex(@"#[0-9a-fA-F]{6,8}")]
    private static partial Regex HexColour();

    [Fact]
    public void The_icon_art_names_no_colour_of_its_own()
    {
        var path = Path.Combine(RepoPaths.Root(), "src", "Alcifra.BrandIcons", "IconArt.cs");
        Assert.True(File.Exists(path), "IconArt.cs not found — if it moved, update this guard.");

        var offenders = HexColour().Matches(File.ReadAllText(path)).Select(m => m.Value).Distinct().ToList();

        Assert.True(
            offenders.Count == 0,
            "IconArt hardcodes " + string.Join(", ", offenders) + ". The launcher icon must take its colours "
            + "from Alcifra.Theming's tokens (ADR 0578), or a brand change leaves the Dock tile wearing "
            + "the previous accent while the application wears the new one.");
    }

    /// <summary>
    /// Every icon the desktop build, the packaging scripts and the API use was generated by the build (ADR 0993) —
    /// this project sets UsesBrandIcons, so the generator ran before these tests compiled.
    /// </summary>
    [Theory]
    [InlineData("icon.png")]
    [InlineData("icon-1024.png")]
    [InlineData("app.ico")]
    [InlineData("app.icns")]
    [InlineData("linux/48.png")]
    [InlineData("linux/64.png")]
    [InlineData("linux/128.png")]
    [InlineData("linux/256.png")]
    [InlineData("web/favicon.png")]
    [InlineData("web/favicon.ico")]
    public void Every_icon_is_generated(string relative)
    {
        var path = Path.Combine(RepoPaths.Root(), "artifacts", "brand-icons", relative.Replace('/', Path.DirectorySeparatorChar));

        Assert.True(File.Exists(path), $"artifacts/brand-icons/{relative} is missing: Alcifra.BrandIcons did not run (ADR 0993).");
        Assert.True(new FileInfo(path).Length > 0, $"artifacts/brand-icons/{relative} is empty.");
    }

    /// <summary>The icons are generated, never committed (ADR 0993): a committed copy would be a second, stale answer.</summary>
    [Theory]
    [InlineData("src/Alcifra.DesktopClient/Assets/cabinet.png")]
    [InlineData("src/Alcifra.DesktopClient/Assets/cabinet-1024.png")]
    [InlineData("src/Alcifra.DesktopClient/Assets/app.ico")]
    [InlineData("src/Alcifra.DesktopClient/Assets/Alcifra.icns")]
    [InlineData("src/Alcifra.DesktopClient/Assets/linux-icons")]
    [InlineData("src/Alcifra.Client/wwwroot/favicon.png")]
    [InlineData("src/Alcifra.Client/wwwroot/favicon.ico")]
    [InlineData("src/Alcifra.Api/wwwroot/download/themes")]
    public void No_generated_icon_is_committed(string relative)
    {
        var path = Path.Combine(RepoPaths.Root(), relative.Replace('/', Path.DirectorySeparatorChar));
        Assert.False(File.Exists(path) || Directory.Exists(path), $"{relative} is back. Icons are generated at build time (ADR 0993); delete it.");
    }
}
