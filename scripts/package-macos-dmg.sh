#!/usr/bin/env bash
#
# Package the Alcifra DesktopClient (Avalonia) as native macOS .app bundles + .dmg installers, one
# each for Apple Silicon (arm64) and Intel (x64). See ADR "macOS .dmg packaging for the desktop client".
#
#   - Self-contained: bundles the .NET runtime, so the target Mac needs no .NET installed.
#   - SIGNED AND NOTARIZED when a Developer ID identity is available (ADR 0896): every Mach-O file signed with
#     the hardened runtime and a timestamp, then the app with scripts/macos/Alcifra.entitlements, then the
#     .dmg, which is notarized and stapled so it opens without Gatekeeper's warning — offline too.
#   - AD-HOC signed otherwise (`codesign -s -`), as every build was before ADR 0896: enough for the Apple
#     Silicon loader to launch it, and Gatekeeper warns on first open. The script says so loudly.
#   - Packaged with the built-in `hdiutil` (no Homebrew dependency); each .dmg contains the .app plus an
#     /Applications symlink for drag-to-install.
#
# Signing is driven by the ENVIRONMENT, never by arguments, so no secret reaches argv or shell history:
#   MACOS_SIGN_IDENTITY   the identity in the keychain, e.g. "Developer ID Application: Name (TEAMID)"
#   NOTARY_APPLE_ID, NOTARY_APP_PASSWORD, APPLE_TEAM_ID   notarytool's Apple ID route (no App Store Connect)
#   REQUIRE_SIGNING=1     refuse to build an unsigned .dmg — the release sets this, so a release cannot ship
#                         an ad-hoc build without saying so by failing.
#
# Usage:   scripts/package-macos-dmg.sh [version] [--upload]
#            version   optional (default 0.1.0) — stamped into the bundle + the .dmg file names.
#            --upload  after building, attach the two .dmgs to the existing GitHub Release v<version> on the
#                      public repo (issue #306). The macOS .dmg CI job is opt-in (needs a pricey macos runner),
#                      so in the common case you build + upload from a Mac; the release itself is created by the
#                      desktop-packages workflow on the v* tag push (with the win/linux archives). Needs `gh`
#                      authenticated with write access. The target repo defaults to HebelConsulting/Alcifra
#                      (override with RELEASE_REPO=…). Idempotent — re-runs replace the assets (--clobber).
#
# Output:  dist/Alcifra-<version>-<arch>.dmg   (arch = arm64 | x64)
#
# Must run on macOS (needs the .app bundle format + hdiutil + codesign).

set -euo pipefail

VERSION="0.1.0"
UPLOAD=0
for arg in "$@"; do
  case "$arg" in
    --upload) UPLOAD=1 ;;
    -*) echo "error: unknown option '$arg' (usage: package-macos-dmg.sh [version] [--upload])." >&2; exit 2 ;;
    *) VERSION="$arg" ;;
  esac
done

# The brand names the bundle and the files (ADR 0994): APP_NAME is the file stem, DISPLAY_NAME what macOS shows.
source "$(dirname "$0")/brand.sh"
APP_NAME="$BRAND_FILE_STEM"
DISPLAY_NAME="$BRAND_NAME"
EXE_NAME="Alcifra.DesktopClient"          # the apphost `dotnet publish` produces (the project name)
BUNDLE_ID="$BRAND_BUNDLE_ID"                  # reverse-DNS bundle identifier
PROJECT="src/Alcifra.DesktopClient/Alcifra.DesktopClient.csproj"
ICNS="artifacts/brand-icons/app.icns"         # generated by the publish below from the brand's icon (ADR 0993)
OUT_DIR="dist"

if [[ "$(uname)" != "Darwin" ]]; then
  echo "error: this script must run on macOS (it needs the .app bundle format, hdiutil and codesign)." >&2
  exit 1
fi

# The macOS target (#2036) is bound to the .NET for macOS pack this solution builds with, and that pack requires ONE
# Xcode version: 27.0.10742 refuses 27.2 ("requires Xcode 27.1"), which is what /Applications/Xcode.app became on
# 2026-10-30. Pin the versioned 27.1 when the environment has not chosen, as the mobile release does (Mobile ADRs
# 0012/0044). WORKAROUND DEPENDENCY (core ADR 0885): retire this block once the installed workload accepts the
# Xcode in /Applications, by setting DEVELOPER_DIR or deleting these lines.
if [[ -z "${DEVELOPER_DIR:-}" && -d /Applications/Xcode_27.1.app/Contents/Developer ]]; then
  export DEVELOPER_DIR=/Applications/Xcode_27.1.app/Contents/Developer
fi

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$repo_root"
mkdir -p "$OUT_DIR"

ENTITLEMENTS="scripts/macos/Alcifra.entitlements"
SIGN_IDENTITY="${MACOS_SIGN_IDENTITY:-}"
if [[ -z "$SIGN_IDENTITY" ]]; then
  if [[ "${REQUIRE_SIGNING:-0}" == 1 ]]; then
    echo "error: REQUIRE_SIGNING=1 but MACOS_SIGN_IDENTITY is empty — refusing to build an unsigned .dmg." >&2
    exit 1
  fi
  echo "==> No MACOS_SIGN_IDENTITY: building AD-HOC signed .dmgs (Gatekeeper will warn on first open)."
elif [[ -z "${NOTARY_APPLE_ID:-}" || -z "${NOTARY_APP_PASSWORD:-}" || -z "${APPLE_TEAM_ID:-}" ]]; then
  # A signed but un-notarized .dmg is WORSE than an ad-hoc one: Gatekeeper still refuses it, and it looks finished.
  echo "error: MACOS_SIGN_IDENTITY is set but NOTARY_APPLE_ID / NOTARY_APP_PASSWORD / APPLE_TEAM_ID are not." >&2
  exit 1
fi

# Developer ID signing, inside-out (ADR 0896). `codesign --deep` is NOT used: it signs nested code with the
# outer call's options, which gives every dylib the app's entitlements, and Apple's notary rejects --deep
# signatures outright. So every file is signed on its own first, then the bundle seals the rest.
#
# EVERY file in Contents/MacOS and Contents/MonoBundle, not only the Mach-O ones. codesign treats everything there
# as nested code, so the self-contained publish's managed assemblies (System.IO.dll and some 240 others) must carry
# a signature too — codesign stores a non-Mach-O file's in its extended attributes. The first dry-run signed Mach-O
# only and the main executable was refused: "code object is not signed at all — In subcomponent: …/System.IO.dll".
# MonoBundle is where the macOS target keeps them, and `codesign --deep` does NOT descend into it — an unsigned
# PDFium there was SIGKILLED at launch on Apple Silicon even for an ad-hoc build, which is why the ad-hoc path
# signs file by file with the same walk.
sign_bundle() {
  local app_dir="$1" exe="$2" identity="$3"
  shift 3
  local file root
  for root in "$app_dir/Contents/MacOS" "$app_dir/Contents/MonoBundle"; do
    [ -d "$root" ] || continue
    while IFS= read -r -d '' file; do
      if [[ "$file" != "$app_dir/Contents/MacOS/$exe" ]]; then
        codesign --force "$@" --sign "$identity" "$file"
      fi
    done < <(find "$root" -type f -print0)
  done
  codesign --force "$@" --sign "$identity" "$app_dir/Contents/MacOS/$exe"
  codesign --force "$@" --sign "$identity" "$app_dir"
  codesign --verify --strict --deep --verbose=2 "$app_dir"
}

# Sign, notarize and staple the .dmg. The password reaches notarytool through its argv, which is unavoidable
# for the Apple ID route; it is never echoed, and on CI the runner masks secrets in its log.
#
# Apple's wait is usually minutes and once ran past the job's whole hour (v0.59.1's first run). So each wait has its own
# limit, NOTARY_WAIT (20 minutes), and a wait that runs out is submitted once more: a new submission rather than waiting
# again, because a submission stuck in the queue may never come out. Any other failure ends the script at once.
NOTARY_WAIT="${NOTARY_WAIT:-20m}"

# The submission's FINAL status, from the last "status:" line notarytool prints for it. Its progress lines read
# "Current status: In Progress..." even when the same output ends "status: Accepted", so a search of the whole output
# for "In Progress" took every accepted submission for a wait that ran out (v0.60.0's first packaging run).
notary_final_status() {
  sed -n 's/^ *status: //p' | tail -1
}

notarize_dmg() {
  local dmg="$1" out submission attempt
  codesign --force --timestamp --sign "$SIGN_IDENTITY" "$dmg"
  for attempt in 1 2; do
    echo "==> Notarizing $(basename "$dmg"), attempt $attempt (this waits for Apple, at most $NOTARY_WAIT)…"
    local answered=1
    out="$(xcrun notarytool submit "$dmg" --apple-id "$NOTARY_APPLE_ID" --password "$NOTARY_APP_PASSWORD" \
      --team-id "$APPLE_TEAM_ID" --wait --timeout "$NOTARY_WAIT" 2>&1)" || answered=0
    # A wait that ran out leaves the submission "In Progress", whether notarytool then exits with an error or not.
    local final
    final="$(notary_final_status <<<"$out")"
    if [[ "$final" == "In Progress" || ( $answered -eq 0 && -z "$final" && "$out" == *[Tt]imeout* ) ]]; then
      echo "$out" >&2
      if [[ $attempt -eq 1 ]]; then
        echo "==> Apple did not answer within $NOTARY_WAIT; submitting once more." >&2
        continue
      fi
      echo "error: Apple did not notarize $(basename "$dmg") within two waits of $NOTARY_WAIT." >&2
      exit 1
    fi
    if [[ $answered -eq 0 ]]; then
      echo "$out" >&2
      exit 1
    fi
    break
  done
  grep -E "id:|status:" <<<"$out" || true   # informational only; must never fail the script
  if [[ "$(notary_final_status <<<"$out")" != "Accepted" ]]; then
    # The notary says WHY in a log the submit output only links to; fetch it, or the refusal is unreadable.
    submission="$(echo "$out" | sed -n 's/^ *id: //p' | head -1)"
    xcrun notarytool log "$submission" --apple-id "$NOTARY_APPLE_ID" --password "$NOTARY_APP_PASSWORD" \
      --team-id "$APPLE_TEAM_ID" >&2 || true
    echo "error: notarization of $(basename "$dmg") was not accepted." >&2
    exit 1
  fi
  xcrun stapler staple "$dmg"
  spctl --assess --type open --context context:primary-signature --verbose=2 "$dmg"
}

# Build one architecture: publish the macOS target -> take the bundle it produces -> our own metadata -> sign -> .dmg.
#
# The macOS package is built from the project's `net10.0-macos` target (#2036): the system's player binds AppKit and
# AVFoundation, which a plain `net10.0` build cannot reference. The target is opt-in (`-p:MacPlayer=true`) because it
# needs the macOS workload, which the Linux build and the whole test matrix must not need. `-p:CreatePackage=false`
# keeps the .app; the Apple SDK would otherwise turn the publish into an installer .pkg.
build_one() {
  local rid="$1" arch_label="$2"
  local stage="$OUT_DIR/stage-$arch_label"
  local app_dir="$stage/${APP_NAME}.app"
  local dmg="$OUT_DIR/${APP_NAME}-${VERSION}-${arch_label}.dmg"
  local bundle="src/Alcifra.DesktopClient/bin/Release/net10.0-macos/$rid/${EXE_NAME}.app"

  echo "==> [$arch_label] Publishing $EXE_NAME ($rid, macOS target, self-contained, Release)…"
  rm -rf "$stage" "$dmg" "$bundle"
  # -p:Version stamps the assembly's InformationalVersion, which is what the client reports as its own version
  # (ClientUpdate) + the update check compares against the release tag — WITHOUT it the build defaults to 1.0.0.
  # The CFBundleVersion below is separate macOS bundle metadata and does NOT affect this.
  dotnet publish "$PROJECT" -c Release -r "$rid" -f net10.0-macos -p:MacPlayer=true -p:CreatePackage=false \
    --self-contained true -p:Version="$VERSION" -p:PublishSingleFile=false -p:DebugType=none -p:DebugSymbols=false
  [ -d "$bundle" ] || { echo "error: the publish produced no bundle at $bundle." >&2; exit 1; }

  echo "==> [$arch_label] Staging ${APP_NAME}.app…"
  mkdir -p "$stage"
  cp -R "$bundle" "$app_dir"
  cp "$ICNS" "$app_dir/Contents/Resources/${APP_NAME}.icns"

  # Every Mach-O in the bundle keeps THIS package's architecture only. Three third-party libraries (AvaloniaNative,
  # SkiaSharp, HarfBuzzSharp) ship universal, so the arm64 package carried Intel code it never loads — which macOS 26
  # reports at launch as "contains a component that will not open on macOS 28" (2026-11-19). The x64 package loses the
  # arm64 halves it cannot use the same way. Signing below signs the thinned files; thinning invalidates the signature.
  local arch=arm64 macho kind archs
  [[ "$rid" == osx-x64 ]] && arch=x86_64
  while IFS= read -r -d '' macho; do
    kind="$(file -b "$macho")"
    case "$kind" in
      *Mach-O*)
        archs="$(lipo -archs "$macho" 2>/dev/null || true)"
        case "$archs" in
          *" "*)
            echo "   thinning $archs → $arch: ${macho#"$app_dir"/}"
            lipo -thin "$arch" -output "$macho.thin" "$macho" && mv "$macho.thin" "$macho"
            ;;
        esac
        ;;
    esac
  done < <(find "$app_dir" -type f -print0)

  # The x64 bundle gets its PDFium dylib from here: the project takes that arch's copy out of the SDK's link and
  # reidentification (its prebuilt x64 binary has no room for the rewritten identity, dotnet/macios#13999), so the
  # runtime finds the file by name in MonoBundle. arm64's comes from the SDK, reidentified like every native library.
  if [[ "$rid" == osx-x64 ]]; then
    local packages pdfium
    packages="$(dotnet nuget locals global-packages --list | sed -n 's/^global-packages: //p')"
    pdfium="$(ls -1 "$packages"/docnet.core/*/runtimes/osx-x64/native/pdfium.dylib 2>/dev/null | sort -V | tail -1)"
    [ -n "$pdfium" ] || { echo "error: no pdfium.dylib for osx-x64 under $packages/docnet.core." >&2; exit 1; }
    cp "$pdfium" "$app_dir/Contents/MonoBundle/pdfium.dylib"
  fi

  # Our bundle metadata, on the bundle the SDK produced (which carries the runtime's own keys, the executable's name
  # and the target's minimum system version): the names, the deep-link scheme (#761) and the version this release is.
  local plist="$app_dir/Contents/Info.plist" pb=/usr/libexec/PlistBuddy
  for key in CFBundleDisplayName CFBundleIconFile NSHighResolutionCapable LSApplicationCategoryType CFBundleURLTypes; do
    $pb -c "Delete :$key" "$plist" 2>/dev/null || true
  done
  $pb -c "Add :CFBundleDisplayName string $DISPLAY_NAME" "$plist"
  $pb -c "Set :CFBundleName $DISPLAY_NAME" "$plist"
  $pb -c "Set :CFBundleIdentifier $BUNDLE_ID" "$plist"
  $pb -c "Set :CFBundleVersion $VERSION" "$plist"
  $pb -c "Set :CFBundleShortVersionString $VERSION" "$plist"
  $pb -c "Add :CFBundleIconFile string $APP_NAME" "$plist"
  $pb -c "Add :NSHighResolutionCapable bool true" "$plist"
  $pb -c "Add :LSApplicationCategoryType string public.app-category.business" "$plist"
  $pb -c "Add :CFBundleURLTypes array" "$plist"
  $pb -c "Add :CFBundleURLTypes:0 dict" "$plist"
  $pb -c "Add :CFBundleURLTypes:0:CFBundleURLName string ${BUNDLE_ID}.deeplink" "$plist"
  $pb -c "Add :CFBundleURLTypes:0:CFBundleURLSchemes array" "$plist"
  $pb -c "Add :CFBundleURLTypes:0:CFBundleURLSchemes:0 string alcifra" "$plist"

  if [[ -n "$SIGN_IDENTITY" ]]; then
    echo "==> [$arch_label] Signing with the Developer ID (hardened runtime)…"
    sign_bundle "$app_dir" "$EXE_NAME" "$SIGN_IDENTITY" --timestamp --options runtime --entitlements "$ENTITLEMENTS"
  else
    # Ad-hoc signature (no Apple account): required for the app to launch on Apple Silicon, where EVERY loaded Mach-O
    # must be signed — the same file-by-file walk as above, without a timestamp or entitlements.
    echo "==> [$arch_label] Ad-hoc signing…"
    sign_bundle "$app_dir" "$EXE_NAME" -
  fi

  # /Applications symlink so the .dmg offers drag-to-install.
  ln -sf /Applications "$stage/Applications"

  echo "==> [$arch_label] Building ${dmg}…"
  hdiutil create -volname "${DISPLAY_NAME} ${VERSION}" -srcfolder "$stage" -ov -format UDZO "$dmg" >/dev/null
  if [[ -n "$SIGN_IDENTITY" ]]; then
    notarize_dmg "$dmg"
  fi

  rm -rf "$stage"
  echo "==> [$arch_label] Done: $dmg"
}

build_one osx-arm64 arm64
build_one osx-x64 x64

arm_dmg="$OUT_DIR/${APP_NAME}-${VERSION}-arm64.dmg"
x64_dmg="$OUT_DIR/${APP_NAME}-${VERSION}-x64.dmg"

echo
echo "Built:"
ls -lh "$arm_dmg" "$x64_dmg"

# --upload (issue #306): attach the two version-matching .dmgs to the existing GitHub Release v<version> on the
# public repo. Only the .dmgs named for THIS version are uploaded — a guard against attaching a stale build to
# the wrong release.
if [[ "$UPLOAD" == 1 ]]; then
  tag="v${VERSION}"
  release_repo="${RELEASE_REPO:-HebelConsulting/Alcifra}"

  command -v gh >/dev/null 2>&1 || { echo "error: '--upload' needs the GitHub CLI ('gh'), authenticated with write access to ${release_repo}." >&2; exit 1; }

  echo
  echo "==> Uploading the macOS .dmg(s) to release ${tag} on ${release_repo}…"
  # The release must already exist (the desktop-packages workflow creates it on the v* tag push, with the
  # win/linux archives); this only ADDS the macOS artifacts the opt-in macOS CI job would otherwise build.
  if ! gh release view "$tag" --repo "$release_repo" >/dev/null 2>&1; then
    echo "error: release '$tag' not found on ${release_repo}. Push the ${tag} tag first (it creates the release), then re-run with --upload." >&2
    exit 1
  fi

  gh release upload "$tag" "$arm_dmg" "$x64_dmg" --clobber --repo "$release_repo"
  echo "==> Uploaded $(basename "$arm_dmg") + $(basename "$x64_dmg") to ${release_repo} ${tag}."
fi

if [[ -n "$SIGN_IDENTITY" ]]; then
  echo
  echo "These .dmg installers are signed with the Developer ID, notarized and stapled."
  exit 0
fi

